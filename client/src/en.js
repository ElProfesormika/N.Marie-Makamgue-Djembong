export function englishNav(slug) {
  return PAGES[slug]?.nav_label || "";
}

export function localizeSite(data) {
  return {
    ...data,
    pages: data.pages.map((page) => ({ ...page, ...(PAGES[page.slug] || {}) })),
    entries: data.entries.map(localizeEntry),
    settings: localizeSettings(data.settings || {}),
  };
}

function localizeEntry(item) {
  if (item.collection === "presence") {
    return {
      ...item,
      titleFr: item.title,
      title: COUNTRIES[item.title] || item.title,
      body: item.title === "États-Unis" ? "Presence in 3 states." : item.body,
    };
  }
  if (item.collection === "ambassades") {
    return { ...item, title: COUNTRIES[item.title] || item.title };
  }
  const pack = ENTRIES[`${item.collection}::${item.title}`];
  if (!pack) return item;
  return {
    ...item,
    ...pack,
    extra: { ...(item.extra || {}), ...(pack.extra || {}) },
  };
}

function localizeSettings(settings) {
  return {
    ...settings,
    brand: { ...(settings.brand || {}), ...SETTINGS.brand },
    hero: { ...(settings.hero || {}), ...SETTINGS.hero },
    sections: { ...(settings.sections || {}), ...SETTINGS.sections },
    contact: { ...(settings.contact || {}), ...SETTINGS.contact },
  };
}
